# The top level walk is fed by a FileStream rather than a byte array, so it
# needs its own fixtures. All three cases below survived a mutation census.
$tlDir = Join-Path $script:Work 'toplevel'
$null = New-Item -ItemType Directory -Path $tlDir

function New-WalkStream {
    param([string] $Name, [byte[]] $Bytes)
    $wp = Join-Path $script:TlDir $Name
    [IO.File]::WriteAllBytes($wp, $Bytes)
    return (New-Object System.IO.FileStream($wp, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, [System.IO.FileShare]::ReadWrite))
}
$script:TlDir = $tlDir

# A 64 bit top level box keeps its real size in the second eight bytes, so
# the walk has to read a sixteen byte header before it can find it.
$bigBytes = [byte[]]((0, 0, 0, 1, 0x66, 0x72, 0x65, 0x65, 0, 0, 0, 0, 0, 0, 0, 24) + (New-Object byte[] 8) + (0, 0, 0, 8, 0x6D, 0x6F, 0x6F, 0x76))
$sBig = New-WalkStream 'big64.mp4' $bigBytes
try {
    $bigErr = ''
    $bx = $null
    try { $bx = @(Get-TopLevelBoxes -Stream $sBig) } catch { $bigErr = $_.Exception.Message }
    Assert-Equal '' $bigErr 'a 64 bit top level box is walked without error'
    Assert-Equal 2 @($bx).Count 'a 64 bit box and the box after it are both walked'
    if (@($bx).Count -eq 2) {
        Assert-Equal 'free' $bx[0].Type 'the 64 bit box keeps its type'
        Assert-Equal 24 $bx[0].Size 'the 64 bit size is read from the second eight bytes'
        Assert-Equal 16 $bx[0].HeaderSize 'a 64 bit box reports a sixteen byte header'
        Assert-Equal 8 $bx[0].BodySize 'the 64 bit body is what is left after the longer header'
        Assert-False $bx[0].Truncated 'a 64 bit box that fits is not truncated'
        Assert-Equal 'moov' $bx[1].Type 'the walk lands on the next box'
        Assert-Equal 24 $bx[1].Offset 'the next box starts where the 64 bit box ended'
    }
} finally { $sBig.Dispose() }

# A recording still being written has a final box claiming more bytes than
# exist. That is reported as truncated, not trusted and not rejected.
$shortBytes = [byte[]]((0, 0, 0, 8, 0x66, 0x74, 0x79, 0x70) + (0, 0, 0, 100, 0x6D, 0x6F, 0x6F, 0x76) + (1, 2, 3, 4))
$sShort = New-WalkStream 'overrun.mp4' $shortBytes
try {
    $sb = @(Get-TopLevelBoxes -Stream $sShort)
    Assert-Equal 2 $sb.Count 'the complete box and the overrunning one are both reported'
    if ($sb.Count -eq 2) {
        Assert-False $sb[0].Truncated 'the complete first box is not marked truncated'
        Assert-True $sb[1].Truncated 'a box claiming more bytes than the file holds is marked truncated'
        Assert-Equal 'moov' $sb[1].Type 'the truncated box keeps its type'
        Assert-Equal 12 $sb[1].Size 'the truncated box is trimmed to what the file actually holds'
        Assert-Equal 20 $sb[1].End 'the truncated box ends at the end of the file'
        Assert-Equal 4 $sb[1].BodySize 'the truncated body is what is left after its header'
    }
} finally { $sShort.Dispose() }


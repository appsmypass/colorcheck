Start-Group 'findings, the exact wording of every measured sentence'

# A census run proved that five of these sentences could have their two
# operands swapped without a single assertion noticing. The words were all
# still present; they were just attached to the wrong side, so the file read
# perfectly and said the opposite of the truth. colorcheck copies Detail
# straight into its JSON, so that is not a cosmetic defect, it is a wrong
# answer in a machine readable field.
#
# Every sentence that interpolates a measured value now gets two assertions:
# the exact text, which pins the wording, and a rule derived from the track
# itself, which stays true if the fixture ever changes.

function Assert-InOrder {
    param([string] $Detail, [string] $First, [string] $Second, [string] $What)
    $a = $Detail.IndexOf($First)
    $b = $Detail.IndexOf($Second)
    Assert-True ($a -ge 0 -and $b -ge 0 -and $a -lt $b) $What
}

$wMatrix = Get-Track1 (New-Fixture 'matrixconflict')
$wMatrixD = (Get-Finding $wMatrix 'MATRIX_CONFLICT').Detail
Assert-Equal ('The colr box says BT.601 525 line (SMPTE 170M) and the bitstream says BT.709. ' +
    'Players that trust the container and players that trust the stream will show different colours for the same file.') `
    $wMatrixD 'the matrix conflict sentence reads exactly as designed'
$wMatrixColr = Get-CodeName -Table $script:MatrixNames -Code $wMatrix.Colr.Matrix
$wMatrixVui  = Get-CodeName -Table $script:MatrixNames -Code $wMatrix.Bitstream.Vui.Matrix
Assert-True ($wMatrixColr -ne $wMatrixVui) 'the matrix conflict fixture really does hold two different values'
Assert-InOrder $wMatrixD $wMatrixColr $wMatrixVui 'the matrix conflict names the container value before the stream value'

$wPrim = Get-Track1 (New-Fixture 'primconflict')

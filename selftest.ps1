<#
    selftest.ps1 - hermetic tests for colorcheck.

    Every file this touches is generated by mp4gen.ps1 in a temporary folder,
    so the answers are known by construction rather than by observation. It
    needs no network, no real recordings and no other tools.

        powershell -NoProfile -ExecutionPolicy Bypass -File selftest.ps1
#>

[CmdletBinding()]
param(
    [string] $Only = '',
    [switch] $StopOnFail
)

$ErrorActionPreference = 'Stop'

$script:Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$script:Tool = Join-Path $script:Root 'colorcheck.ps1'
$script:Gen  = Join-Path $script:Root 'mp4gen.ps1'

if (-not (Test-Path $script:Tool)) { throw "colorcheck.ps1 not found next to selftest.ps1" }
if (-not (Test-Path $script:Gen))  { throw "mp4gen.ps1 not found next to selftest.ps1" }


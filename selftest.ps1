# Read-At is the only place a short read can happen. A local disk practically
# never produces one on its own, so it is forced here by asking for more bytes
# than the file holds. Without these the tool would silently zero fill.
$ratPath = Join-Path $script:Work 'readat.bin'
[IO.File]::WriteAllBytes($ratPath, [byte[]](1, 2, 3, 4, 5, 6, 7, 8))
$rs = New-Object System.IO.FileStream($ratPath, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, [System.IO.FileShare]::ReadWrite)
try {
    Assert-Equal 8 $rs.Length 'the read fixture is eight bytes'
    $whole = Read-At -Stream $rs -Position 0 -Count 8
    Assert-Equal 8 $whole.Length 'a full read returns every byte asked for'
    Assert-Equal 1 $whole[0] 'the first byte of a full read is right'
    Assert-Equal 8 $whole[7] 'the last byte of a full read is right'
    $tail = Read-At -Stream $rs -Position 4 -Count 4
    Assert-Equal 4 $tail.Length 'a read that ends exactly at the end is allowed'
    Assert-Equal 5 $tail[0] 'a read at an offset starts in the right place'
    $emptyRead = @(Read-At -Stream $rs -Position 0 -Count 0)
    Assert-Equal 0 $emptyRead.Count 'a zero length read is allowed and empty'
    Assert-Throws { Read-At -Stream $rs -Position 4 -Count 8 } 'wanted 8 bytes at 4, got 4' 'a read that runs off the end is refused rather than zero filled'
    Assert-Throws { Read-At -Stream $rs -Position 0 -Count 9 } 'wanted 9 bytes at 0, got 8' 'a read one byte longer than the file is refused'
    Assert-Throws { Read-At -Stream $rs -Position 8 -Count 1 } 'past the end of a 8 byte file' 'a seek to exactly the end of the file is refused'
    Assert-Throws { Read-At -Stream $rs -Position 9 -Count 1 } 'past the end of a 8 byte file' 'a seek past the end of the file is refused'
    Assert-Throws { Read-At -Stream $rs -Position -1 -Count 1 } 'negative position' 'a negative position is refused'
    Assert-Throws { Read-At -Stream $rs -Position 0 -Count -1 } 'negative count' 'a negative count is refused'
} finally {
    $rs.Dispose()

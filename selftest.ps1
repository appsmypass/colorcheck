# ---------------------------------------------------------------------------
# Load colorcheck's own functions without running its entry point, so the
# small pieces can be tested directly rather than only through the console
# output. The cut point is the entry point banner, which is a fixed string.
# ---------------------------------------------------------------------------

function Import-ToolLibrary {
    $src = [IO.File]::ReadAllText($script:Tool)
    $marker = '# Entry point.'
    $cut = $src.IndexOf($marker)
    if ($cut -lt 0) { throw "selftest: could not find the entry point marker in colorcheck.ps1" }
    $lib = $src.Substring(0, $cut)

    $pstart = $lib.IndexOf('[CmdletBinding()]')
    if ($pstart -lt 0) { throw "selftest: could not find the param block in colorcheck.ps1" }
    $anchor = $lib.IndexOf('[switch] $Help')
    if ($anchor -lt 0) { throw "selftest: could not find the end of the param block" }
    $pend = $lib.IndexOf(')', $anchor)
    if ($pend -lt 0) { throw "selftest: could not find the closing paren of the param block" }

    $lib = $lib.Substring(0, $pstart) + $lib.Substring($pend + 1)
    return [scriptblock]::Create($lib)
}

. (Import-ToolLibrary)


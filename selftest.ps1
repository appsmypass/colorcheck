# The three colour codes are stored twice, once in the container and once in
# the bitstream, and each has to be compared against its own counterpart.
# Comparing primaries against the matrix is invisible on a file where both
# happen to be 1, so the fixtures below deliberately pull them apart.
function New-ColourTrack {
    param([int] $CP, [int] $CT, [int] $CM, [int] $VP, [int] $VT, [int] $VM)
    return [pscustomobject]@{
        Colr = [pscustomobject]@{ Kind = 'nclx'; Primaries = $CP; Transfer = $CT; Matrix = $CM; FullRange = $false }
        Bitstream = [pscustomobject]@{
            Vui = [pscustomobject]@{
                Present = $true; Block = $true; VideoFormat = 5; FullRange = $false
                Primaries = $VP; Transfer = $VT; Matrix = $VM
            }
        }
    }
}

function Test-FindingsHaveCode {
    param($Findings, [string] $Code)
    # An empty finding list comes back as $null, and @($null) is an array of
    # one null rather than an empty array, so the null has to go first.
    if ($null -eq $Findings) { return $false }
    return (@(@($Findings) | Where-Object { $null -ne $_ -and $_.Code -eq $Code }).Count -gt 0)
}


# The sample description count is a 32 bit field read straight out of the file,
# and it drives a loop. A corrupt or hostile value of four billion does not
# crash - the loop just breaks on the first out of bounds entry - so the file
# is quietly reported as having no video track at all. Refusing an absurd count
# turns a silent wrong answer into a named parse error.
function Find-Fourcc {
    param([byte[]] $Bytes, [string] $Cc)
    $t = [byte[]][char[]]$Cc
    for ($i = 0; $i -le $Bytes.Length - 4; $i++) {
        if ($Bytes[$i] -eq $t[0] -and $Bytes[$i+1] -eq $t[1] -and $Bytes[$i+2] -eq $t[2] -and $Bytes[$i+3] -eq $t[3]) { return $i }
    }
    return -1
}


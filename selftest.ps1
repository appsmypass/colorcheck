function Get-Codes {
    param($Track)
    return @($Track.Findings | ForEach-Object { $_.Code })
}

function Test-HasCode {
    param($Track, [string] $Code)
    return (@(Get-Codes $Track) -ccontains $Code)
}

function Get-Finding {
    param($Track, [string] $Code)
    foreach ($f in $Track.Findings) { if ($f.Code -ceq $Code) { return $f } }
    return $null
}

# Run the published command line in a child process. Slower than calling the
# functions directly, so it is used only where the command line itself is the
# thing under test.
function Invoke-Cli {
    param([string[]] $CliArgs)
    $all = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $script:Tool) + $CliArgs
    $out = & powershell @all 2>&1 | Out-String
    return [pscustomobject]@{ Out = $out; Exit = $LASTEXITCODE }
}

# A child process whose stdout is redirected to a file is the only way to see
# whether colour was used: Windows console colour is an api call, not an escape
# sequence, so a piped capture looks identical either way. With a redirected
# handle the coloured lines still reach the file but with a bare line feed,
# which is enough to tell two runs apart.
function Invoke-CliToFile {
    param([string[]] $CliArgs)
    $out = Join-Path $env:TEMP ('cc-cliout-' + [guid]::NewGuid().ToString('N') + '.txt')
    $all = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $script:Tool) + $CliArgs
    Start-Process -FilePath 'powershell' -ArgumentList $all -NoNewWindow -Wait -RedirectStandardOutput $out
    $text = [IO.File]::ReadAllText($out)
    Remove-Item $out -Force -ErrorAction SilentlyContinue
    return $text
}

function Write-RawFile {
    param([string] $Name, [byte[]] $Bytes)
    $path = Join-Path $script:Work $Name
    [IO.File]::WriteAllBytes($path, $Bytes)
    return $path
}


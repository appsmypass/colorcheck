# A fixture is built once and then looked up by name. Asking for a name that
# has not been built, without saying how to build it, is a mistake in the test
# rather than something to paper over with a default file, because a silently
# wrong fixture turns a real failure into a pass.
function New-Fixture {
    param([Parameter(Mandatory = $true)][string] $Name, [hashtable] $Options = @{})
    if ($script:Fixtures.ContainsKey($Name)) { return $script:Fixtures[$Name] }
    if ($Options.Count -eq 0 -and $Name -ne 'clean709') {
        throw ("selftest: fixture '" + $Name + "' was asked for before it was defined")
    }
    $path = Join-Path $script:Work ($Name + '.mp4')
    $opt = @{} + $Options
    $opt['LiteralPath'] = $path
    New-SimpleMp4 @opt | Out-Null
    $script:Fixtures[$Name] = $path
    return $path
}


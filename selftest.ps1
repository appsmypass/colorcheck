$script:Passed = 0
$script:Failed = 0
$script:Failures = New-Object System.Collections.ArrayList
$script:Group = ''
$script:GroupCount = 0

function Start-Group {
    param([string] $Name)
    $script:Group = $Name
    $script:GroupCount++
    Write-Host ("[" + $script:GroupCount + "] " + $Name) -ForegroundColor Cyan
}

function Test-Skip {
    if ($Only -eq '') { return $false }
    return ($script:Group -notlike ('*' + $Only + '*'))
}

function Pass {
    param([string] $What)
    $script:Passed++
}

function Fail {
    param([string] $What, [string] $Detail)
    $script:Failed++
    $line = '    FAIL [' + $script:Group + '] ' + $What
    Write-Host $line -ForegroundColor Red
    if ($Detail -ne '') { Write-Host ('           ' + $Detail) -ForegroundColor DarkRed }
    [void]$script:Failures.Add($line + ' :: ' + $Detail)
    if ($StopOnFail) {
        # Stopping has to tidy up after itself. The mutation harness runs this
        # suite once per mutant, and a failure that skipped the cleanup would
        # leave a folder of fixtures behind every single time.
        Write-Host ''
        Write-Host ('  stopped on the first failure after ' + $script:Passed + ' passed') -ForegroundColor Red
        Remove-Item $script:Work -Recurse -Force -ErrorAction SilentlyContinue
        exit 1
    }
}

function Assert-Equal {
    param($Expected, $Actual, [string] $What)
    if (Test-Skip) { return }
    $e = $(if ($null -eq $Expected) { '<null>' } else { [string]$Expected })
    $a = $(if ($null -eq $Actual) { '<null>' } else { [string]$Actual })
    if ($e -ceq $a) { Pass $What } else { Fail $What ("expected '" + $e + "' but got '" + $a + "'") }
}

function Assert-True {
    param($Condition, [string] $What)
    if (Test-Skip) { return }
    if ($Condition) { Pass $What } else { Fail $What 'expected true' }
}

function Assert-False {
    param($Condition, [string] $What)
    if (Test-Skip) { return }
    if (-not $Condition) { Pass $What } else { Fail $What 'expected false' }
}

function Assert-Null {
    param($Value, [string] $What)
    if (Test-Skip) { return }
    if ($null -eq $Value) { Pass $What } else { Fail $What ("expected null but got '" + $Value + "'") }
}

function Assert-NotNull {
    param($Value, [string] $What)
    if (Test-Skip) { return }
    if ($null -ne $Value) { Pass $What } else { Fail $What 'expected a value but got null' }
}

function Assert-Match {
    param([string] $Text, [string] $Pattern, [string] $What)
    if (Test-Skip) { return }
    if ($null -ne $Text -and $Text -match $Pattern) { Pass $What }
    else { Fail $What ("'" + $Pattern + "' did not match") }
}

function Assert-NotMatch {
    param([string] $Text, [string] $Pattern, [string] $What)
    if (Test-Skip) { return }
    if ($null -eq $Text -or $Text -notmatch $Pattern) { Pass $What }
    else { Fail $What ("'" + $Pattern + "' matched but should not have") }
}

function Assert-Throws {
    param([scriptblock] $Body, [string] $Pattern, [string] $What)
    if (Test-Skip) { return }
    $threw = $false
    $msg = ''
    try { & $Body } catch { $threw = $true; $msg = $_.Exception.Message }
    if (-not $threw) { Fail $What 'expected an exception, none was thrown'; return }
    if ($Pattern -ne '' -and $msg -notmatch $Pattern) {
        Fail $What ("threw '" + $msg + "' which does not match '" + $Pattern + "'")
        return
    }
    Pass $What
}


# Effective tags. The container colr box is the tag a player reads first, so
# its range flag has to reach the effective answer even when nothing else in
# the file states a range.
function New-RangeTrack {
    param($ColrRange, [bool] $VuiPresent, $VuiRange)
    $vui = $null
    if ($VuiPresent) {
        $vui = [pscustomobject]@{
            Present = $true; Primaries = $null; Transfer = $null; Matrix = $null; FullRange = $VuiRange
        }
    }
    return [pscustomobject]@{
        Colr = [pscustomobject]@{
            Kind = 'nclx'; Primaries = $null; Transfer = $null; Matrix = $null; FullRange = $ColrRange
        }
        Bitstream = [pscustomobject]@{ Vui = $vui }
    }
}

$rangeOnlyColr = Get-EffectiveTags -Track (New-RangeTrack -ColrRange $true -VuiPresent $false -VuiRange $null)
Assert-True $rangeOnlyColr.FullRange 'a container range with no bitstream still reaches the effective tags'
Assert-Equal 'container' $rangeOnlyColr.Source 'a container only range is sourced from the container'
Assert-Equal 'full (0-255)' $rangeOnlyColr.RangeName 'a container only range is named rather than left unknown'

$rangeLimited = Get-EffectiveTags -Track (New-RangeTrack -ColrRange $false -VuiPresent $false -VuiRange $null)
Assert-False $rangeLimited.FullRange 'a container limited range reaches the effective tags'
Assert-Equal 'container' $rangeLimited.Source 'a container limited range is sourced from the container'

# When both state a range the container wins, because that is what a player
# obeys before it has decoded a single frame.
$rangeBoth = Get-EffectiveTags -Track (New-RangeTrack -ColrRange $false -VuiPresent $true -VuiRange $true)
Assert-False $rangeBoth.FullRange 'the container range overrides the bitstream range'
Assert-Equal 'bitstream' $rangeBoth.Source 'a range only container does not claim the tag source'

$rangeBoth2 = Get-EffectiveTags -Track (New-RangeTrack -ColrRange $true -VuiPresent $true -VuiRange $false)
Assert-True $rangeBoth2.FullRange 'the container full range overrides a limited bitstream'

